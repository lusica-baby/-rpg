# ---- 事件词汇 ----
#
# NPC 的 `lines` 里，除了一句台词（str），还可以放**动作元组**：
#
#   ("给", "片纸")              获得 1 个
#   ("给", "片纸", 3)           获得 3 个
#   ("收", "青麻头")            失去 1 个（P5 虫毙于盆中要用）
#   ("收", "青麻头", 2)         失去 2 个
#   ("开", "失虫")              打开全局开关
#   ("声", {音频对象})          在这一步播 SE（事件级那个 se 是**无条件**播的，
#                               要"只在某条分支上响"就得用这个）
#   ("乐", {音频对象})          在这一步播 ME。与 SE 的区别只有一点，但很关键：
#                               ME 会让正在播的 BGM **让位**，播完自动接回来 ——
#                               这正是「情绪拐点」要的效果（P5 的 Shock3、P7 的 Victory1）
#   ("分支", 条件, 真段)
#   ("分支", 条件, 真段, 假段)   真段 / 假段本身又是**一串 lines**，所以能嵌套
#
# 条件现在有两种：
#
#   ("道具", "片纸")            $gameParty.hasItem($dataItems[id])
#   ("开关", "失虫")            $gameSwitches.value(id)
#
# **为什么没有变量、也没有"关"**：变量是给数值累加用的，本作一个数都不用存；
# 而四个开关都是单向的一次性事实（虫死过、井边演过、斗过、献过），
# 开了就不该再关。真需要时再加，各三行。
#
# 台词在分支里的写法：连续的 str 会被合成**一段文字框**（101 + 401*），
# 中间夹一个动作就断成两段。这是 MZ 的硬规矩 —— command101 会一口气
# 吃掉紧跟其后的所有 401，所以每一段都得有自己的 101。

