def events_of(mid):
    """一张图上的全部事件，**顺序即 id**（从 1 起）。

    构建器与走查工具都从这里取顺序。两边各排一次的话，一旦排法不同，
    事件 id 与名字就会错位 —— 而错位只会表现为「截图标题写错了名字」，
    不报错、不崩，就这么一直错下去。所以顺序只留一处。

    NPC 排在前面、门/路口排在后面，是为了让已有的截图编号（04-成妻、05-成子…）
    在加传送门之后保持不变。
    返回 [(kind, 数据元组), ...]，kind 是 "npc" 或 "portal"。
    """
    md = MAPS[mid]
    return ([("npc", t) for t in md.get("npcs", [])] +
            [("portal", t) for t in md.get("portals", [])])


def event_names(mid):
    """事件 id -> 名字。两个数据元组的第 0 位都是名字，所以能共用一行。"""
    return {i: t[0] for i, (_kind, t) in enumerate(events_of(mid), 1)}


def walk_lines(lines):
    """递归遍历一串 lines，产出其中**每一个**元素 —— 包括各分支里的。

    给「数一数这条事件会响哪些 SE」这类体检用。分支里的东西不能漏：
    漏了不会报错，只会让某个 SE 变成"没人验的 SE"。
    """
    for it in lines:
        yield it
        if isinstance(it, tuple) and it[0] == "分支":
            for seg in it[2:]:
                for x in walk_lines(seg):
                    yield x


def audio_cues(mid):
    """一张图上**全部会响的**音频，产出 (类别, 名字)：类别是 "se" 或 "me"。

    走查拿它当期望值。只数事件级会漏掉分支里的 —— 石穴那个 Water2 就是从
    事件级搬进分支的（事件级 SE 是无条件播的，无片纸时也会"哗"一声），
    漏收等于把一个 SE 变成没人验的。

    ("乐", …) 是 ME，跟 SE 落在同一个数组里（instrument.js 把
    playSe/playMe 都包了同一层），所以这里必须一起收 —— 只收 SE 的话，
    P5 那几个 ME 就成了"响了但没人验"。

    **连类别一起收**，是因为只对名字就会漏掉一类错：把 ("乐", …) 错写成
    ("声", …) 时，名字照样对得上、断言照样全绿，只有听感不对（ME 会让
    BGM 让位再自动接回，SE 是硬插一声）。这正是本工程反复吃亏的那种
    「不报错但全错」，所以类别必须进断言。
    """
    out = []
    for kind, t in events_of(mid):
        if kind != "npc":
            continue
        if t[7]:
            out.append(("se", t[7]["name"]))      # 事件级那个字段是 SE，不是 ME
        for it in walk_lines(t[6]):
            if isinstance(it, tuple) and it[0] in ("声", "乐"):
                out.append(("se" if it[0] == "声" else "me", it[1]["name"]))
    return out

